import os
import subprocess
import xml.etree.ElementTree as ET

def build_network():
    os.makedirs(os.path.dirname(os.path.abspath(__file__)), exist_ok=True)
    
    grid_size = 6
    spacing = 300
    
    # Generate Nodes
    nodes_xml = ['<nodes>']
    
    for row in range(grid_size):
        for col in range(grid_size):
            node_id = f"TL{row * grid_size + col + 1}"
            x = col * spacing
            y = (grid_size - 1 - row) * spacing
            nodes_xml.append(f'    <node id="{node_id}" x="{x}" y="{y}" type="traffic_light"/>')
            
    # Peripheral nodes
    for col in range(grid_size):
        x = col * spacing
        nodes_xml.append(f'    <node id="top{col+1}" x="{x}" y="{grid_size * spacing}" type="priority"/>')
        nodes_xml.append(f'    <node id="bot{col+1}" x="{x}" y="-{spacing}" type="priority"/>')
        
    for row in range(grid_size):
        y = (grid_size - 1 - row) * spacing
        nodes_xml.append(f'    <node id="left{row+1}" x="-{spacing}" y="{y}" type="priority"/>')
        nodes_xml.append(f'    <node id="right{row+1}" x="{grid_size * spacing}" y="{y}" type="priority"/>')
        
    nodes_xml.append('</nodes>')
    
    with open('net.nod.xml', 'w') as f:
        f.write('\n'.join(nodes_xml))
        
    # Generate Edges
    edges_xml = ['<edges>']
    num_lanes = 3
    speed = 13.89
    
    def add_edge(from_node, to_node):
        edges_xml.append(f'    <edge id="{from_node}_{to_node}" from="{from_node}" to="{to_node}" numLanes="{num_lanes}" speed="{speed}"/>')
        edges_xml.append(f'    <edge id="{to_node}_{from_node}" from="{to_node}" to="{from_node}" numLanes="{num_lanes}" speed="{speed}"/>')

    # Internal edges
    for row in range(grid_size):
        for col in range(grid_size):
            curr_id = f"TL{row * grid_size + col + 1}"
            if col < grid_size - 1:
                right_id = f"TL{row * grid_size + col + 2}"
                add_edge(curr_id, right_id)
            if row < grid_size - 1:
                bottom_id = f"TL{(row + 1) * grid_size + col + 1}"
                add_edge(curr_id, bottom_id)
                
    # Peripheral edges
    for col in range(grid_size):
        top_tl = f"TL{col + 1}"
        top_periph = f"top{col + 1}"
        add_edge(top_periph, top_tl)
        
        bot_tl = f"TL{5 * grid_size + col + 1}"
        bot_periph = f"bot{col + 1}"
        add_edge(bot_periph, bot_tl)
        
    for row in range(grid_size):
        left_tl = f"TL{row * grid_size + 1}"
        left_periph = f"left{row + 1}"
        add_edge(left_periph, left_tl)
        
        right_tl = f"TL{row * grid_size + 6}"
        right_periph = f"right{row + 1}"
        add_edge(right_periph, right_tl)

    edges_xml.append('</edges>')
    
    with open('net.edg.xml', 'w') as f:
        f.write('\n'.join(edges_xml))
        
    # Connections (optional, netconvert handles standard grids well)
    # But since we have 3 lanes, let's explicitly request left-turn lanes.
    print("Compiling network with netconvert...")
    subprocess.run([
        'netconvert',
        '--node-files=net.nod.xml',
        '--edge-files=net.edg.xml',
        '--output-file=net.net.xml',
        '--tls.guess', 'true',
        '--tls.default-type', 'static',
        '--default.lanenumber', str(num_lanes),
        '--default.speed', str(speed)
    ], check=True)
    
    patch_tls()
    
    print("Network compilation complete: net.net.xml generated.")

def patch_tls():
    net_file = "net.net.xml"
    tree = ET.parse(net_file)
    root = tree.getroot()
    
    # With 3 lanes per edge, 4 incoming edges = 12 lanes.
    # Typically, netconvert allocates 1 left turn, 1 straight, 1 right turn (or straight/right combined).
    # A standard 4-phase program for 4 edges (N,S,E,W) with dedicated left turns:
    # We must match the string length generated by netconvert.
    # First, let's find the length of the state string for the first phase generated by netconvert.
    first_tl = root.find('tlLogic')
    if first_tl is not None:
        first_phase = first_tl.find('phase')
        state_len = len(first_phase.get('state'))
        print(f"Detected TLS state string length: {state_len}")
        
        # We need to construct custom phases.
        # However, netconvert's default 4-phase static cycle is often exactly what we need:
        # Phase 0: NS Green
        # Phase 1: NS Yellow
        # Phase 2: EW Green
        # Phase 3: EW Yellow
        # If we need NS Left, we might need a 8-phase cycle. 
        # Netconvert automatically creates an 8-phase cycle if left turns are heavily conflicting.
        # Let's inspect how many phases netconvert generated.
        phases = first_tl.findall('phase')
        print(f"Netconvert generated {len(phases)} phases.")
        
        # If it generated 8 phases, we assume it's [NS, NS_Y, NS_L, NS_L_Y, EW, EW_Y, EW_L, EW_L_Y]
        # Wait, the action mapping in sumo_env_6x6 is 0->0, 1->2, 2->4, 3->6.
        # If netconvert already generates an 8-phase cycle, we don't need to patch anything except maybe standardize durations!
        for i, p in enumerate(phases):
            if i % 2 == 0:
                # Green phase
                p.set('duration', '40')
            else:
                # Yellow phase
                p.set('duration', '5')
                
        tree.write(net_file, encoding="UTF-8", xml_declaration=True)
        print("Standardized TLS durations.")

if __name__ == "__main__":
    build_network()
