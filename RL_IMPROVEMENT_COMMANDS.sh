#!/bin/bash
# RL IMPROVEMENT PIPELINE - EXECUTABLE COMMANDS
# Copy and paste these commands to run the complete pipeline

# Navigate to project root
cd /path/to/intenrship_IIIT

# ==============================================================================
# PHASE 1: DIAGNOSTICS (5 minutes)
# Analyze current model behavior to confirm root causes
# ==============================================================================

echo "=== PHASE 1: DIAGNOSTICS ==="
python smart_city_ai/tools/rl_diagnostic.py --agent ddqn --steps 500
python smart_city_ai/tools/rl_diagnostic.py --agent ppo --steps 500
python smart_city_ai/tools/rl_diagnostic.py --compare

# Expected output:
# - Q-value statistics showing if models are learning
# - Action distribution showing decision diversity
# - Reward signal quality verification


# ==============================================================================
# PHASE 2: TRAINING WITH IMPROVED HYPERPARAMETERS (3-4 hours)
# Train all three algorithms with optimized settings
# ==============================================================================

echo "=== PHASE 2: TRAINING ==="

# Option A: Sequential (safest, ~4 hours)
python smart_city_ai/tools/enhanced_training.py \
  --agent dqn \
  --seeds 101 202 303 404 505 \
  --episodes 250

python smart_city_ai/tools/enhanced_training.py \
  --agent ddqn \
  --seeds 101 202 303 404 505 \
  --episodes 250 \
  --lr 2e-4 \
  --batch-size 128

python smart_city_ai/tools/enhanced_training.py \
  --agent ppo \
  --seeds 101 202 303 404 505 \
  --episodes 250 \
  --entropy-coef 0.05

# Option B: Parallel (faster if system supports it, ~1.5 hours)
# NOTE: Only if you have sufficient GPU memory or are using CPU
(
  python smart_city_ai/tools/enhanced_training.py \
    --agent dqn --seeds 101 202 303 --episodes 250 &
  python smart_city_ai/tools/enhanced_training.py \
    --agent ddqn --seeds 101 202 303 --episodes 250 --lr 2e-4 &
  python smart_city_ai/tools/enhanced_training.py \
    --agent ppo --seeds 101 202 303 --episodes 250 --entropy-coef 0.05 &
  wait
)

# Expected output in results/rl_training/:
# - {agent}_training_metrics.csv (episode, reward, wait, queue, etc.)
# - {agent}_training_summary.json (best reward, final metrics)
# - {agent}_model_best.pth (saved checkpoint)
# - {agent}_model_final.pth (final model)


# ==============================================================================
# PHASE 3: COMPREHENSIVE BENCHMARK (30-60 minutes)
# Evaluate all trained models against baseline
# ==============================================================================

echo "=== PHASE 3: BENCHMARK ==="

python smart_city_ai/tools/rl_comprehensive_benchmark.py \
  --duration 600 \
  --seeds 101 202 303 404 505 \
  --output results/rl_benchmark

# Expected output:
# - benchmark_results.csv (all metrics with std dev and CI)
# - benchmark_report.json (statistics, rankings, improvements)
# - Console output with summary table


# ==============================================================================
# PHASE 4: GENERATE FINAL REPORT (2 minutes)
# Auto-generated by master pipeline, but can be run separately
# ==============================================================================

echo "=== PHASE 4: REPORTS ==="

# Master pipeline generates these automatically:
# results/RL_IMPROVEMENT_REPORT.md (markdown with analysis)
# results/RL_IMPROVEMENT_REPORT.json (structured data)

# View results:
cat results/RL_IMPROVEMENT_REPORT.md


# ==============================================================================
# ALTERNATIVE: RUN ENTIRE PIPELINE AUTOMATICALLY
# ==============================================================================

# One command to run everything:
python smart_city_ai/tools/rl_improvement_pipeline.py

# Or with options:
python smart_city_ai/tools/rl_improvement_pipeline.py --skip-training  # Use existing models
python smart_city_ai/tools/rl_improvement_pipeline.py --only-benchmark  # Only eval
python smart_city_ai/tools/rl_improvement_pipeline.py --diagnostics-only  # Only diagnose


# ==============================================================================
# QUICK VALIDATION (30 minutes - for fast feedback)
# ==============================================================================

# Just want to see if improvements work? Run this quick version:

echo "=== QUICK VALIDATION ==="

# 1. Diagnostic (5 min)
python smart_city_ai/tools/rl_diagnostic.py --agent ddqn

# 2. Quick training (20 min - single seed, 100 episodes)
python smart_city_ai/tools/enhanced_training.py \
  --agent ddqn \
  --seed 101 \
  --episodes 100 \
  --lr 2e-4

# 3. Quick benchmark (5 min - single seed, short duration)
python smart_city_ai/tools/rl_comprehensive_benchmark.py \
  --duration 300 \
  --seeds 101

# Check results in results/rl_benchmark/benchmark_report.json


# ==============================================================================
# MONITORING DURING TRAINING
# ==============================================================================

# In a separate terminal, watch training progress:

# Watch DQN training:
watch -n 5 "tail -20 results/rl_training/dqn_training_metrics.csv"

# Watch DDQN training:
watch -n 5 "tail -20 results/rl_training/ddqn_training_metrics.csv"

# Watch PPO training:
watch -n 5 "tail -20 results/rl_training/ppo_training_metrics.csv"

# Or just tail without watch:
tail -f results/rl_training/ddqn_training_metrics.csv


# ==============================================================================
# ANALYZE RESULTS
# ==============================================================================

# View final report:
cat results/RL_IMPROVEMENT_REPORT.md

# View detailed statistics:
cat results/rl_benchmark/benchmark_report.json | python -m json.tool

# View CSV results (with column headers):
head -5 results/rl_benchmark/benchmark_results.csv
cat results/rl_benchmark/benchmark_results.csv

