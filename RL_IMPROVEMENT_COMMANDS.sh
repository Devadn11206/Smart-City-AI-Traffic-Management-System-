# Generate comparison table:
python -c "
import json
import pandas as pd

with open('results/rl_benchmark/benchmark_report.json', 'r') as f:
    data = json.load(f)

# Extract statistics
stats = data['statistics']
results = []
for agent, metrics in stats.items():
    results.append({
        'Agent': agent.upper(),
        'Wait (s)': f\"{metrics['wait']['mean']:.2f}±{metrics['wait']['std']:.2f}\",
        'Queue': f\"{metrics['queue']['mean']:.2f}±{metrics['queue']['std']:.2f}\",
        'Speed': f\"{metrics['avg_speed']['mean']:.2f}\",
        'Throughput': f\"{metrics['throughput']['mean']:.0f}±{metrics['throughput']['std']:.0f}\",
    })

df = pd.DataFrame(results)
print(df.to_string(index=False))
print()

# Improvements vs baseline
if 'improvements_vs_baseline' in data:
    print('Improvements vs Fixed-Time:')
    for agent, improvement in data['improvements_vs_baseline'].items():
        direction = '↓' if improvement > 0 else '↑'
        print(f\"  {agent.upper():8} {direction} {abs(improvement):.1f}%\")
"


